function genStudents(cls, count, seed){
  var r = rng(seed), out = [];
  var year = cls.indexOf("高一")>=0 ? "2007" : (cls.indexOf("高二")>=0 ? "2006" : "2005");
  var prefix = year === "2007" ? "07" : year === "2006" ? "06" : "05";
  for (var i=0;i<count;i++){
    var cnum = cls.replace(/[^0-9]/g,"");
    out.push({
      id: prefix + cnum + (100+i).toString(),
      name: genName(r),
      gender: r()>0.5 ? "男" : "女",
      cls: cls,
      status: "在读"
    });
  }
  return out;
}
